"""Migration of a DevRoute (v0.1, v0.2) installation by `susanoo init`."""

from __future__ import annotations

import json
import shutil
from pathlib import Path

import pytest

from susanoo.adapters.claude_code import legacy
from susanoo.adapters.claude_code.installer import sha256, skill_template
from susanoo.config import read_data_text
from susanoo.paths import find_project_root
from tests.conftest import write
from tests.test_cli import run

OLD_SKILL = ".claude/skills/devroute/SKILL.md"
OLD_AGENTS = (".claude/agents/devroute-reviewer.md", ".claude/agents/devroute-researcher.md")
OLD_FILES = {
    OLD_SKILL: "---\nname: devroute\n---\nold skill\n",
    OLD_AGENTS[0]: "old reviewer\n",
    OLD_AGENTS[1]: "old researcher\n",
    ".devroute/config.toml": "# DevRoute project configuration\n",
    ".devroute/.gitignore": "# DevRoute local state (generated by devroute init)\nrecords/\ninstall.json\n",
}
NEW_SKILL = ".claude/skills/susanoo/SKILL.md"


@pytest.fixture(autouse=True)
def isolated_home(monkeypatch: pytest.MonkeyPatch, home: Path) -> None:
    monkeypatch.setenv("HOME", str(home))
    monkeypatch.setenv("USERPROFILE", str(home))


def devroute_install(root: Path, enforce: object = True) -> None:
    """What DevRoute v0.2 left on disk, including its manifest and a route record."""
    for rel, text in OLD_FILES.items():
        write(root, rel, text)
    write(root, ".devroute/records/routes.jsonl", '{"id": "dr-1", "session_id": "s"}\n')
    manifest = {
        "files": {rel: sha256(text) for rel, text in OLD_FILES.items()},
        "enforce": enforce,
        "devroute_version": "0.2.0",
    }
    write(root, ".devroute/install.json", json.dumps(manifest))


def actions_of(out: str) -> list[tuple[str, str]]:
    return [(a["path"], a["action"]) for a in json.loads(out)["actions"]]


def test_init_migrates_devroute_install(tmp_path: Path):
    devroute_install(tmp_path)
    code, out, _ = run(tmp_path, "init")
    assert code == 0
    assert "Migrated the DevRoute installation" in out
    assert not (tmp_path / ".devroute").exists()
    # Records survive; old ids keep working.
    assert "dr-1" in (tmp_path / ".susanoo/records/routes.jsonl").read_text(encoding="utf-8")
    # Unmodified DevRoute files are removed, and their empty directory with them.
    assert not (tmp_path / ".claude/skills/devroute").exists()
    assert not any((tmp_path / rel).exists() for rel in OLD_AGENTS)
    # The enforce choice carries over, and unmodified state files are updated to Susanoo's.
    assert (tmp_path / NEW_SKILL).read_text(encoding="utf-8") == skill_template(True)
    assert (tmp_path / ".susanoo/config.toml").read_text(encoding="utf-8") == read_data_text(
        "templates", "config.toml"
    )
    assert "Susanoo" in (tmp_path / ".susanoo/.gitignore").read_text(encoding="utf-8")
    manifest = json.loads((tmp_path / ".susanoo/install.json").read_text(encoding="utf-8"))
    assert manifest["enforce"] is True
    assert manifest["migrated_from"] == {"devroute_version": "0.2.0"}
    # A second run has nothing left to migrate.
    _, out, _ = run(tmp_path, "init")
    assert "Migrated" not in out


def test_dry_run_matches_the_real_run(tmp_path: Path):
    devroute_install(tmp_path / "a")
    write(tmp_path / "a", ".devroute/config.toml", "[routing]\n# mine\n")
    shutil.copytree(tmp_path / "a", tmp_path / "b")
    _, preview, _ = run(tmp_path / "a", "init", "--dry-run", "--json")
    _, real, _ = run(tmp_path / "b", "init", "--json")
    assert actions_of(preview) == actions_of(real)
    assert (".devroute/", "migrate") in actions_of(preview)
    assert (".susanoo/config.toml", "conflict") in actions_of(preview)
    # Nothing was written by the preview.
    assert (tmp_path / "a/.devroute").is_dir() and (tmp_path / "a" / OLD_SKILL).is_file()
    assert not (tmp_path / "a/.susanoo").exists()
    _, text, _ = run(tmp_path / "a", "init", "--dry-run")
    assert "Will migrate the DevRoute installation" in text


def test_failed_move_changes_nothing(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    devroute_install(tmp_path)

    def locked(*_: object) -> None:
        raise PermissionError("[WinError 5] Access is denied")

    monkeypatch.setattr(legacy.os, "replace", locked)
    code, _, err = run(tmp_path, "init")
    assert code == 1
    assert "could not migrate .devroute/" in err and "internal error" not in err
    assert (tmp_path / OLD_SKILL).is_file() and (tmp_path / ".devroute/install.json").is_file()
    assert not (tmp_path / NEW_SKILL).exists()


def test_modified_devroute_files_are_kept(tmp_path: Path):
    devroute_install(tmp_path)
    write(tmp_path, OLD_AGENTS[0], "my edits\n")
    write(tmp_path, ".devroute/config.toml", "[routing]\n# mine\n")
    _, out, _ = run(tmp_path, "init", "--json")
    actions = dict(actions_of(out))
    assert actions[OLD_AGENTS[0]] == "keep-modified"
    assert actions[".susanoo/config.toml"] == "conflict"
    assert (tmp_path / OLD_AGENTS[0]).read_text(encoding="utf-8") == "my edits\n"
    assert (tmp_path / ".susanoo/config.toml").read_text(encoding="utf-8") == "[routing]\n# mine\n"
    assert not (tmp_path / OLD_SKILL).exists()


def test_shipped_devroute_files_are_removed_without_a_manifest(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
):
    # A teammate who cloned a repository with the committed /devroute skill has no install.json.
    shipped = "---\nname: devroute\n---\nas shipped\n"
    monkeypatch.setitem(legacy.SHIPPED, OLD_SKILL, frozenset({sha256(shipped)}))
    write(tmp_path, OLD_SKILL, shipped)
    write(tmp_path, OLD_AGENTS[0], "someone's own agent\n")
    _, out, _ = run(tmp_path, "init", "--json")
    actions = dict(actions_of(out))
    assert actions[OLD_SKILL] == "remove" and not (tmp_path / OLD_SKILL).exists()
    assert actions[OLD_AGENTS[0]] == "keep-modified" and (tmp_path / OLD_AGENTS[0]).is_file()


def test_teammate_records_merge_into_committed_susanoo_state(tmp_path: Path):
    # Teammate A committed the migration; B's pull removed .devroute/'s tracked files but left
    # B's local records and install.json behind.
    devroute_install(tmp_path, enforce=True)
    for rel in (".devroute/config.toml", ".devroute/.gitignore"):
        (tmp_path / rel).unlink()
    write(tmp_path, ".devroute/records/hooks/s.json", '{"record_id": "dr-1"}')
    write(tmp_path, ".susanoo/config.toml", read_data_text("templates", "config.toml"))
    write(tmp_path, ".susanoo/records/routes.jsonl", '{"id": "su-1"}\n')
    _, out, _ = run(tmp_path, "init", "--json")
    assert (".devroute/", "merge") in actions_of(out)
    routes = (tmp_path / ".susanoo/records/routes.jsonl").read_text(encoding="utf-8")
    assert "su-1" in routes and "dr-1" in routes
    assert (tmp_path / ".susanoo/records/hooks/s.json").is_file()
    assert not (tmp_path / ".devroute").exists()
    # B's enforce choice carries over because Susanoo had none recorded yet.
    assert (tmp_path / NEW_SKILL).read_text(encoding="utf-8") == skill_template(True)


def test_merge_keeps_files_devroute_did_not_create(tmp_path: Path):
    devroute_install(tmp_path)
    write(tmp_path, ".devroute/notes.txt", "mine\n")
    write(tmp_path, ".susanoo/records/routes.jsonl", "")
    _, out, _ = run(tmp_path, "init")
    assert "still has files Susanoo did not create" in out
    assert (tmp_path / ".devroute/notes.txt").is_file()
    assert not (tmp_path / ".devroute/records").exists()


def test_flags_override_the_carried_over_enforce_choice(tmp_path: Path):
    devroute_install(tmp_path, enforce=True)
    run(tmp_path, "init", "--no-enforce")
    assert (tmp_path / NEW_SKILL).read_text(encoding="utf-8") == skill_template(False)


def test_non_boolean_enforce_in_legacy_manifest_is_off(tmp_path: Path):
    devroute_install(tmp_path, enforce="false")
    run(tmp_path, "init")
    assert (tmp_path / NEW_SKILL).read_text(encoding="utf-8") == skill_template(False)


def test_untrusted_legacy_manifest_cannot_remove_other_files(tmp_path: Path):
    devroute_install(tmp_path)
    write(tmp_path, ".claude/settings.json", '{"permissions": {}}')
    manifest = json.loads((tmp_path / ".devroute/install.json").read_text(encoding="utf-8"))
    manifest["files"][".claude/settings.json"] = sha256('{"permissions": {}}')
    write(tmp_path, ".devroute/install.json", json.dumps(manifest))
    run(tmp_path, "init")
    assert (tmp_path / ".claude/settings.json").is_file()


def test_no_agents_still_removes_old_subagents(tmp_path: Path):
    devroute_install(tmp_path)
    run(tmp_path, "init", "--no-agents")
    assert not any((tmp_path / rel).exists() for rel in OLD_AGENTS)
    assert not (tmp_path / ".claude/agents/susanoo-reviewer.md").exists()


def test_uninstall_removes_devroute_files_too(tmp_path: Path):
    devroute_install(tmp_path)
    _, out, _ = run(tmp_path, "init", "--uninstall", "--json")
    assert (OLD_SKILL, "remove") in actions_of(out)
    assert not (tmp_path / OLD_SKILL).exists()


def test_legacy_state_marks_the_project_root(tmp_path: Path):
    devroute_install(tmp_path)
    (tmp_path / "src").mkdir()
    assert find_project_root(tmp_path / "src") == tmp_path.resolve()


def test_doctor_warns_about_devroute_leftovers(tmp_path: Path, home: Path):
    devroute_install(tmp_path)
    hook = {"type": "command", "command": "devroute hook session-start"}
    write(tmp_path, ".claude/settings.local.json", {"hooks": {"SessionStart": [{"hooks": [hook]}]}})
    _, out, _ = run(tmp_path, "doctor", "--json")
    checks = {c["check"]: c for c in json.loads(out)["checks"]}
    assert checks["DevRoute installation"]["status"] == "warn"
    assert "settings.local.json" in checks["DevRoute hook in settings"]["detail"]


def test_shipped_state_files_update_without_a_manifest(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    devroute_install(tmp_path)
    (tmp_path / ".devroute/install.json").unlink()
    config = OLD_FILES[".devroute/config.toml"]
    monkeypatch.setitem(legacy.SHIPPED, ".devroute/config.toml", frozenset({sha256(config)}))
    _, out, _ = run(tmp_path, "init", "--json")
    assert (".susanoo/config.toml", "update") in actions_of(out)
