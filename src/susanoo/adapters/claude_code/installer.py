"""Safe project installation of the Susanoo Claude Code integration.

Rules:
- Only Susanoo-owned files are written: the /susanoo skill, the taste-ui skill, susanoo-* subagents,
  and files under .susanoo/. CLAUDE.md and .mcp.json are never touched; settings only with the
  opt-in settings enforcement scope (see settings_hooks.py), and then only Susanoo's own entries.
- Existing files are never overwritten unless they are unmodified Susanoo installs
  (hash matches the install manifest) or ``force`` is given, in which case a backup
  copy is written first.
- Uninstall removes only files whose content still matches what Susanoo installed.
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import tempfile
from dataclasses import asdict, dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from susanoo import __version__
from susanoo.config import read_data_text
from susanoo.paths import install_manifest_path, state_dir

GITIGNORE = "# Susanoo local state (generated by susanoo init)\nrecords/\ninstall.json\n"


@dataclass(frozen=True)
class Target:
    path: str  # relative to the project root, POSIX separators
    content: str
    optional_group: str | None = None


@dataclass
class FileAction:
    path: str
    # create | update | unchanged | conflict | overwrite | remove | keep-modified | absent
    action: str
    note: str = ""

    @property
    def writes(self) -> bool:
        return self.action in ("create", "update", "overwrite")


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def skill_template(enforce: bool = False) -> str:
    """The /susanoo skill; with ``enforce`` its frontmatter also registers the enforcement hooks.

    Hooks declared in skill frontmatter are registered when the skill is invoked and stay
    active while that Claude Code process runs (not after a later ``claude --resume``), so
    enforcement only applies to /susanoo sessions and no settings file has to change. The
    settings scope (settings_hooks.py) leaves the skill without hooks, so they never run twice.
    """
    text = read_data_text("templates", "skills", "susanoo", "SKILL.md")
    if not enforce:
        return text
    hooks = read_data_text("templates", "skills", "susanoo", "enforcement-hooks.yaml")
    end = text.index("\n---\n", 3)
    return text[: end + 1] + hooks.rstrip("\n") + "\n" + text[end + 1 :]


SCOPES = ("skill", "settings")


def taste_skill_template() -> str:
    """The taste-ui skill: how Claude makes visual decisions for UI work (see susanoo.taste)."""
    return read_data_text("templates", "skills", "taste-ui", "SKILL.md")


def targets(with_agents: bool = True, enforce: bool = False, with_taste: bool = True) -> list[Target]:
    """Files to install; ``enforce`` puts the hooks in the skill (the default "skill" scope)."""
    items = [
        Target(".claude/skills/susanoo/SKILL.md", skill_template(enforce)),
        Target(".susanoo/config.toml", read_data_text("templates", "config.toml")),
        Target(".susanoo/.gitignore", GITIGNORE),
    ]
    if with_taste:
        items.append(Target(".claude/skills/taste-ui/SKILL.md", taste_skill_template(), "taste"))
    if with_agents:
        for name in ("susanoo-reviewer", "susanoo-researcher"):
            items.append(
                Target(
                    f".claude/agents/{name}.md", read_data_text("templates", "agents", f"{name}.md"), "agents"
                )
            )
    return items


def read_manifest(root: Path) -> dict[str, Any]:
    path = install_manifest_path(root)
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {"files": {}}
    if not isinstance(data, dict) or not isinstance(data.get("files"), dict):
        return {"files": {}}
    # The manifest lives in the repository and is untrusted: only Susanoo's own target
    # paths are honored, so a crafted manifest cannot point at files elsewhere.
    known = {t.path for t in targets(with_agents=True)}
    data["files"] = {k: v for k, v in data["files"].items() if k in known and isinstance(v, str)}
    return data


UNREADABLE = "\x00unreadable"


def _read(path: Path) -> str | None:
    """File text, ``None`` if absent, or ``UNREADABLE`` (binary, directory, no permission)."""
    try:
        return path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None
    except (UnicodeDecodeError, OSError):
        return UNREADABLE


def enforcement_enabled(root: Path) -> bool:
    """Whether the last install used --enforce (later `init` runs keep that choice)."""
    return read_manifest(root).get("enforce") is True


def enforcement_scope(root: Path) -> str:
    """Where the last install put the hooks: "skill" (frontmatter) or "settings" (local settings)."""
    scope = read_manifest(root).get("enforce_scope")
    return scope if scope in SCOPES else "skill"


def update_manifest(root: Path, **fields: Any) -> None:
    manifest = read_manifest(root)
    manifest.update(fields)
    _atomic_write(install_manifest_path(root), json.dumps(manifest, indent=2, sort_keys=True) + "\n")


def plan_install(
    root: Path,
    *,
    force: bool = False,
    with_agents: bool = True,
    enforce: bool = False,
    with_taste: bool = True,
) -> list[FileAction]:
    """Plan an install."""
    manifest = read_manifest(root)["files"]
    actions: list[FileAction] = []
    for target in targets(with_agents, enforce, with_taste):
        current = _read(root / target.path)
        if current is None:
            actions.append(FileAction(target.path, "create"))
        elif current == UNREADABLE:
            note = "existing path is not a readable text file; left untouched"
            actions.append(FileAction(target.path, "conflict", note))
        elif current == target.content:
            actions.append(FileAction(target.path, "unchanged"))
        elif manifest.get(target.path) == sha256(current):
            actions.append(FileAction(target.path, "update", "unmodified previous version"))
        elif force:
            actions.append(FileAction(target.path, "overwrite", "existing file will be backed up first"))
        else:
            actions.append(
                FileAction(
                    target.path,
                    "conflict",
                    "existing file differs; left untouched (use --force to back up and replace)",
                )
            )
    return actions


def _atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def apply_install(
    root: Path,
    actions: list[FileAction],
    *,
    with_agents: bool = True,
    enforce: bool = False,
    scope: str = "skill",
    with_taste: bool = True,
) -> list[FileAction]:
    content = {t.path: t.content for t in targets(with_agents, enforce and scope == "skill", with_taste)}
    manifest = read_manifest(root)
    files: dict[str, str] = manifest["files"]
    stamp = datetime.now(UTC).strftime("%Y%m%d%H%M%S")
    for action in actions:
        path = root / action.path
        if action.action == "overwrite":
            backup = path.with_name(f"{path.name}.susanoo-backup-{stamp}")
            shutil.copy2(path, backup)
            action.note = f"backup written to {backup.relative_to(root).as_posix()}"
        if action.writes:
            _atomic_write(path, content[action.path])
        if action.writes or action.action == "unchanged":
            files[action.path] = sha256(content[action.path])
    manifest.update(
        {
            "susanoo_version": __version__,
            "updated_at": datetime.now(UTC).isoformat(timespec="seconds"),
            "enforce": enforce,
            "enforce_scope": scope,
        }
    )
    _atomic_write(install_manifest_path(root), json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    return actions


def plan_uninstall(root: Path) -> list[FileAction]:
    manifest = read_manifest(root)["files"]
    known: dict[str, set[str]] = {}
    for variant in (False, True):
        for t in targets(with_agents=True, enforce=variant):
            known.setdefault(t.path, set()).add(sha256(t.content))
    actions: list[FileAction] = []
    for rel in sorted(known):
        current = _read(root / rel)
        if current is None:
            if rel in manifest:
                actions.append(FileAction(rel, "absent"))
            continue
        if current == UNREADABLE:
            actions.append(FileAction(rel, "keep-modified", "not a readable text file; left in place"))
            continue
        digest = sha256(current)
        if digest == manifest.get(rel) or digest in known.get(rel, set()):
            actions.append(FileAction(rel, "remove"))
        else:
            actions.append(FileAction(rel, "keep-modified", "modified since installation; left in place"))
    return actions


def apply_uninstall(root: Path, actions: list[FileAction]) -> list[FileAction]:
    for action in actions:
        if action.action == "remove":
            path = root / action.path
            path.unlink()
            parent = path.parent
            while parent != root and parent.is_dir() and not any(parent.iterdir()):
                parent.rmdir()
                parent = parent.parent
    remaining = [a for a in actions if a.action == "keep-modified"]
    manifest_path = install_manifest_path(root)
    if remaining:
        manifest = read_manifest(root)
        manifest["files"] = {a.path: manifest["files"].get(a.path, "") for a in remaining}
        _atomic_write(manifest_path, json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    else:
        manifest_path.unlink(missing_ok=True)
    sdir = state_dir(root)
    if sdir.is_dir() and not any(sdir.iterdir()):
        sdir.rmdir()
    return actions


def actions_to_dicts(actions: list[FileAction]) -> list[dict[str, Any]]:
    return [asdict(a) for a in actions]
